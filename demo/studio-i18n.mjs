export function localeFor({ saved = null, languages = [] } = {}) {
  if (saved === 'ru' || saved === 'en') return saved;
  for (const candidate of languages) {
    const root = String(candidate).toLowerCase().split(/[-_]/)[0];
    if (root === 'ru' || root === 'en') return root;
  }
  return 'ru';
}
export function translate(locale, key) {
  const table = translations[locale];
  if (!table) throw new RangeError('unsupported locale');
  if (!Object.hasOwn(table, key)) throw new RangeError('missing localization key: ' + key);
  return table[key];
}
export function validateTranslations() {
  const ru = Object.keys(translations.ru).sort();
  const en = Object.keys(translations.en).sort();
  if (ru.join('\0') !== en.join('\0')) throw new Error('localization catalog key mismatch');
  if ([...Object.values(translations.ru), ...Object.values(translations.en)].some(v => !v.trim())) {
    throw new Error('empty localization string');
  }
  return ru.length;
}
